/**
 * Cookie の受け渡し形式(純関数)。`kb cookies export --format` で使う。
 *
 * kb 自身は Playwright 形式(JSON)で足りるが、外部ツール(curl / 各種スキャナ)は
 * cookies.txt(Netscape 形式)か `Name=Value; …` の 1 行を受け取ることが多く、
 * JSON 配列だと利用側に必ず変換処理が要る。その変換をここで吸収する。
 */

/** Playwright の context.cookies() が返す形。 */
export interface KbCookie {
  name: string;
  value: string;
  domain: string;
  path: string;
  /** UNIX 秒。セッション Cookie は -1。 */
  expires: number;
  httpOnly: boolean;
  secure: boolean;
  sameSite?: string;
}

/** セッション Cookie(expires<=0)は期限切れ扱いしない。 */
function isExpired(c: KbCookie, nowSec: number): boolean {
  return c.expires > 0 && c.expires < nowSec;
}

/**
 * Netscape 形式(curl / wget の cookies.txt)。
 * httpOnly は curl 互換の `#HttpOnly_` プレフィックスで表す(コメントに見えるが curl は解釈する)。
 */
export function toNetscape(cookies: KbCookie[], opts: { version?: string } = {}): string {
  const lines = [
    '# Netscape HTTP Cookie File',
    '# https://curl.se/docs/http-cookies.html',
    `# generated by kb${opts.version ? ` ${opts.version}` : ''}`,
    '',
  ];
  for (const c of cookies) {
    const includeSubdomains = c.domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const expires = c.expires > 0 ? Math.floor(c.expires) : 0;
    const fields = [c.domain, includeSubdomains, c.path || '/', c.secure ? 'TRUE' : 'FALSE', String(expires), c.name, c.value];
    lines.push(`${c.httpOnly ? '#HttpOnly_' : ''}${fields.join('\t')}`);
  }
  return lines.join('\n') + '\n';
}

/** RFC 6265 のドメイン照合(先頭ドット付きはサブドメインにもマッチ)。 */
export function domainMatches(cookieDomain: string, host: string): boolean {
  const d = cookieDomain.toLowerCase();
  const h = host.toLowerCase();
  if (d.startsWith('.')) return h === d.slice(1) || h.endsWith(d);
  return h === d;
}

/** RFC 6265 のパス照合(/a は /a, /a/b にマッチするが /ab にはマッチしない)。 */
export function pathMatches(cookiePath: string, urlPath: string): boolean {
  const cp = cookiePath || '/';
  if (urlPath === cp) return true;
  if (!urlPath.startsWith(cp)) return false;
  return cp.endsWith('/') || urlPath[cp.length] === '/';
}

/** その URL のリクエストで実際に送られる Cookie か。 */
export function cookieMatchesUrl(c: KbCookie, url: string, nowSec = Math.floor(Date.now() / 1000)): boolean {
  let u: URL;
  try {
    u = new URL(url);
  } catch {
    return false;
  }
  if (isExpired(c, nowSec)) return false;
  if (c.secure && u.protocol !== 'https:') return false;
  return domainMatches(c.domain, u.hostname) && pathMatches(c.path, u.pathname);
}

/**
 * `Name=Value; Name2=Value2` の 1 行(リクエストの Cookie ヘッダそのもの)。
 * url を渡すとその URL に送られる Cookie だけに絞る(jar 全体をそのまま 1 行にすると
 * 別ドメインの Cookie まで混ざって不正になるため、絞り込みは呼び出し側で必須)。
 * 同名 Cookie は RFC 6265 の送出順(パスが長いものを先)に倣って 1 つに寄せる。
 */
export function toCookieHeader(cookies: KbCookie[], url?: string, nowSec = Math.floor(Date.now() / 1000)): string {
  const matched = (url ? cookies.filter((c) => cookieMatchesUrl(c, url, nowSec)) : cookies.filter((c) => !isExpired(c, nowSec)))
    .slice()
    .sort((a, b) => (b.path || '/').length - (a.path || '/').length);
  const seen = new Set<string>();
  const out: string[] = [];
  for (const c of matched) {
    if (seen.has(c.name)) continue;
    seen.add(c.name);
    out.push(`${c.name}=${c.value}`);
  }
  return out.join('; ');
}
